"""Appendix tables of manuscript v5 (v1 results E4, E6, E8, E9) generated from the result CSVs (C6, P6 01-11-2026).

Writes <paper>/generated/tab_app_{e8,e9,e6,e4}.tex (tabular bodies only; captions stay in main.tex).

Usage: python scripts/make_appendix_tables.py --paper <Q1 ESWA Submission>
"""
import argparse
import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
EXT = REPO / "results" / "extended"
CLASSES = ["helmet", "no_helmet", "vest", "no_vest", "gloves", "no_gloves", "goggles", "no_goggles",
           "boots", "no_boots", "mask", "no_mask"]


def rows(p):
    with open(p, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def tex(s):
    return s.replace("_", r"\_")


def e8():
    R = rows(EXT / "e8_perclass_f1_FULL_5models.csv")
    models = ["VGG16", "ResNet50", "GRU-256", "ViT-S/16", "ViT-B/16"]
    by = {(r["model"], r["class"]): r for r in R}
    names = sorted({r["model"] for r in R})
    pick = {m: next(n for n in names if n.startswith(m)) for m in models}
    out = [r"\begin{tabular}{lrccccc}", r"\toprule",
           "Class & Support & " + " & ".join(models) + r" \\", r"\midrule"]
    for c in CLASSES:
        sup = by[(pick["ViT-B/16"], c)]["support"]
        out.append(f"{tex(c)} & {int(float(sup))} & " +
                   " & ".join(f"{float(by[(pick[m], c)]['f1']):.3f}" for m in models) + r" \\")
    return out + [r"\bottomrule", r"\end{tabular}"]


def e9():
    R = {r["class"]: r for r in rows(EXT / "e9_frcnn_perclass.csv")}
    out = [r"\begin{tabular}{lcccrrr}", r"\toprule",
           r"Class & AP@50--95 & Prec.@0.5 & Rec.@0.5 & TP & FP & FN \\", r"\midrule"]
    for c in CLASSES:
        r = R[c]
        out.append(f"{tex(c)} & {float(r['AP50_95']):.3f} & {float(r['precision@0.5']):.3f} & "
                   f"{float(r['recall@0.5']):.3f} & {r['TP']} & {r['FP']} & {r['FN']}" + r" \\")
    return out + [r"\bottomrule", r"\end{tabular}"]


def e6():
    R = rows(EXT / "e6_resolution.csv")
    cols = ["AP50_goggles", "AP50_no_goggles", "AP50_gloves", "AP50_no_gloves"]
    out = [r"\begin{tabular}{lcccccccc}", r"\toprule",
           r"Arm & imgsz & mAP@50 & mAP@50--95 & goggles & no\_goggles & gloves & no\_gloves & min \\", r"\midrule"]
    for r in R:
        out.append(f"{r['arm']} & {r['imgsz']} & {float(r['mAP50_test']):.4f} & {float(r['mAP50_95_test']):.4f} & " +
                   " & ".join(f"{float(r[k]):.4f}" for k in cols) + f" & {float(r['min']):.1f}" + r" \\")
    return out + [r"\bottomrule", r"\end{tabular}"]


def e4():
    R = rows(EXT / "e4_seeds.csv")
    # seed 42 is the E1 reference run of notebook 01: its training time is in results/summary_01_CNN.csv
    ref = next(r for r in rows(REPO / "results" / "summary_01_CNN.csv") if r["model"].startswith("YOLO26s"))
    out = [r"\begin{tabular}{cccc}", r"\toprule", r"Seed & mAP@50 & mAP@50--95 & Train min \\", r"\midrule"]
    for r in R:
        m = r["min"] or (ref["train_min"] if r["seed"] == "42" else "")
        mins = f"{float(m):.1f}" if m else "--"
        out.append(f"{r['seed']} & {float(r['mAP50_test']):.4f} & {float(r['mAP50_95_test']):.4f} & {mins}" + r" \\")
    return out + [r"\bottomrule", r"\end{tabular}"]


def perclass():
    """Tab. perclass (E1 per-class AP@50, two classes per row); the two classes with the lowest mean AP in bold."""
    with open(EXT / "e1_perclass_ap50.csv", encoding="utf-8") as f:
        R = {r["class"]: r for r in csv.DictReader(line for line in f if not line.startswith("#"))}
    low = sorted(CLASSES, key=lambda c: float(R[c]["ap50_yolo26s"]) + float(R[c]["ap50_rtdetr_l"]))[:2]
    def cell(c):
        v = [f"{float(R[c][k]):.3f}" for k in ("ap50_yolo26s", "ap50_rtdetr_l")]
        if c in low:
            v = [rf"\textbf{{{x}}}" for x in v]
        b = int(R[c]["boxes_test"])
        return f"{tex(c)} & {b:,}".replace(",", "{,}") + " & " + " & ".join(v)
    out = [r"\begin{tabular}{lrcc@{\hskip 0.8em}lrcc}", r"\toprule",
           r"Class & Boxes & YOLO26s & RT-DETR & Class & Boxes & YOLO26s & RT-DETR \\", r"\midrule"]
    for a, b in zip(CLASSES[:6], CLASSES[6:]):
        out.append(cell(a) + " & " + cell(b) + r" \\")
    return out + [r"\bottomrule", r"\end{tabular}"]


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", required=True)
    a = ap.parse_args()
    g = Path(a.paper) / "generated"
    for name, fn in (("e8", e8), ("e9", e9), ("e6", e6), ("e4", e4), ("perclass", perclass)):
        body = ["% Generated by scripts/make_appendix_tables.py from results/extended -- do not edit by hand."] + fn()
        (g / f"tab_app_{name}.tex").write_text("\n".join(body) + "\n", encoding="utf-8", newline="\n")
        print(f"tab_app_{name}.tex: {len(body) - 6} rows")
